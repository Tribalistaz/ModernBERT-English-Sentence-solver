            Users can get this recommendation through an app, which can record Points of Interest(POI) from time to time. The app only sends hashed POI and its category (so the server in fact doesn't know what the POI the user visited at any time) as well as an unique uuid (which cannot backtrack to anyone) for the service to match the wandering behaviour patterns and provide recommendations. <br><br>
