              We are strictly against the idea of collecting user sensitive data from the device. We only collect user's POI(Point of Interest) from time to time and send its hash value to the server. It is impossible to obtain the original data from a hash value due to no matter how long (in terms of the number of characters) the original data has, the hash value size is same. It might take 5 years for a computer to brute force a hashed point of interest (see <a href="https://irontechsecurity.com/how-long-does-it-take-a-hacker-to-brute-force-a-password/">HOW LONG DOES IT TAKE A HACKER TO BRUTE FORCE A PASSWORD?</a>) if and only if the hash method is not considering to add salt or making any alternation (see <a href="https://auth0.com/blog/adding-salt-to-hashing-a-better-way-to-store-passwords/">Adding Salt to Hashing: A Better Way to Store Passwords</a>). So no one include us could know what POI you have been before. Additionally, you can remove any POIs that you have been to, permanently at anytime from your device and the server.
              </p>
            </div>
